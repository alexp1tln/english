all_past_questions = []
lesson_counter = 1

for l in raw_lessons:
    l_questions = []
    
    q_index = 1
    for q in l['questions']:
        q_id = f"q{lesson_counter}_{q_index}"
        q_index += 1
        
        q_obj = None
        if q[0] == "MC":
            q_obj = {
                "id": q_id,
                "type": "multiple_choice",
                "question": q[1],
                "options": q[2],
                "correctAnswerIndex": q[3]
            }
        elif q[0] == "FB":
            q_obj = {
                "id": q_id,
                "type": "fill_in_blank",
                "question": q[1],
                "correctAnswer": q[2]
            }
        elif q[0] == "DD":
            opts = q[2][:]
            if len(q) > 3:
                opts.extend(q[3])
            random.shuffle(opts)
            q_obj = {
                "id": q_id,
                "type": "drag_and_drop",
                "question": q[1],
                "options": opts,
                "correctSentence": q[2]
            }
        l_questions.append(q_obj)
        all_past_questions.append(q_obj)
        
    if len(all_past_questions) > len(l_questions):
        past_pool = [pq for pq in all_past_questions if pq not in l_questions]
        if past_pool:
            rep_q = random.choice(past_pool)
            rep_q_copy = dict(rep_q)
            rep_q_copy['id'] = f"q{lesson_counter}_rep"
            # 8 questions per lesson: 7 new, 1 old.
            l_questions.append(rep_q_copy)

    l_words = []
    sel_words = random.sample(words_db, 2)
    for w in sel_words:
        w_obj = {
            "id": f"v_{lesson_counter}_{w[0]}",
            "word": w[0],
            "transcription": w[1],
            "translation": w[2],
            "category": "Basic"
        }
        l_words.append(w_obj)
        
    final_lessons.append({
        "id": f"l{lesson_counter}",
        "title": f"Урок {lesson_counter}: {l['title']}",
        "moduleId": l['module'],
        "theory": l['theory'],
        "words": l_words,
        "quiz": l_questions
    })
    lesson_counter += 1

unique_vocab = []
seen = set()
for l in final_lessons:
    for w in l['words']:
        if w['word'] not in seen:
            seen.add(w['word'])
            unique_vocab.append(w)

